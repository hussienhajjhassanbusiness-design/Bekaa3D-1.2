import type { Metadata } from "next";
import "./globals.css";
import { QueryProvider } from "@/lib/query/QueryProvider";
import { ToastProvider } from "@/components/feedback/ToastProvider";
import { AppLayout } from "@/components/layout/AppLayout";
import { Header } from "@/components/layout/Header";
import { Footer } from "@/components/layout/Footer";
import { BackendUnreachableBanner } from "@/components/feedback/BackendUnreachableBanner";
import { GlobalWhatsAppButton } from "@/components/layout/GlobalWhatsAppButton";
import { AuthProvider } from "@/lib/auth/AuthProvider";

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// FVS001-T14 — the composition root: the only file that knows about every
// FVS-001 piece at once (FRONTEND-VERTICAL-SLICE-PLAN.md §18). Stays a
// Server Component itself (no 'use client') — Server Components may render
// Client Component children, so QueryProvider/ToastProvider/AppLayout's own
// client boundaries are sufficient; nothing here needs client-only APIs.
//
// The `process.env.NODE_ENV === "development"` check below is the one and
// only place in the whole slice that decides whether the readiness banner
// exists in a given build at all — BackendUnreachableBanner itself contains
// no such check (an internal early-return after calling useReadiness() would
// still run its polling in production, and conditionally calling a hook
// would violate the Rules of Hooks). Production simply never mounts the
// component.
export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html lang="en">
      <body>
        <QueryProvider>
          <AuthProvider>
            <ToastProvider>
              <AppLayout header={<Header />} footer={<Footer />}>
                {process.env.NODE_ENV === "development" ? <BackendUnreachableBanner /> : null}
                {children}
                <GlobalWhatsAppButton />
              </AppLayout>
            </ToastProvider>
          </AuthProvider>
        </QueryProvider>
      </body>
    </html>
  );
}
